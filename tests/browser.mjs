import {chromium} from 'playwright';
import {readFile, mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';

const base=process.env.KIKER_TEST_URL || 'http://127.0.0.1:8766';
const fixtures=path.resolve(process.argv[2] || '../kiker-quick-check');
const output=path.resolve(process.argv[3] || '../kiker-browser-checks');
await mkdir(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const page=await context.newPage();
page.setDefaultTimeout(15000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const checks=[];
function pass(check){checks.push({check,passed:true}); console.log('PASS',check);}
try {
 await page.goto(base);
 await page.locator('#upload-view').waitFor({state:'visible'});
 await page.locator('#submit-review').click();
 assert.match(await page.locator('#notice').innerText(),/Добавьте файл/);
 assert.equal(await page.evaluate(()=>document.activeElement.id),'document-text');
 pass('empty input gives a focused, readable error');
 await page.locator('#load-sample').click();
 assert.match(await page.locator('#document-text').inputValue(),/31 января/);
 await page.locator('#clear-input').click();
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:path.join(output,'01-upload.png'),fullPage:true});
 await page.locator('#import-file').setInputFiles(path.join(fixtures,'kiker-january-conflict-1.json'));
 await page.locator('#review-view').waitFor({state:'visible'});
 assert.equal(await page.locator('#metric-total').innerText(),'1');
 assert.equal(await page.locator('.quote').count(),2);
 assert.match(await page.locator('#run-origin').innerText(),/СОХРАНЁННЫЙ/);
 const conflictId=(await page.locator('#download-report').getAttribute('href')).split('/')[3];
 pass('saved real Gemini result imports with two source quotes');
 await page.locator('input[name=decision][value=accepted]').check();
 await page.locator('#decision-note').fill('Месяц учёта — январь. Исправить ожидаемый результат приёмки.');
 await page.getByRole('button',{name:'Сохранить решение',exact:true}).click();
 await page.getByText('Решение сохранено',{exact:true}).waitFor();
 await page.reload();
 await page.locator('#review-view').waitFor({state:'visible'});
 assert.equal(await page.locator('input[name=decision][value=accepted]').isChecked(),true);
 assert.match(await page.locator('#decision-note').inputValue(),/Месяц учёта — январь/);
 assert.equal(await page.locator('#metric-reviewed').innerText(),'1 / 1');
 pass('analyst decision and comment persist across reload');
 await page.locator('input[name=decision][value=pending]').check();
 await page.getByRole('button',{name:'Сохранить решение',exact:true}).click();
 await page.getByText('Решение сохранено',{exact:true}).waitFor();
 await page.locator('#finding-filter').selectOption('pending');
 await page.locator('input[name=decision][value=accepted]').check();
 await page.getByRole('button',{name:'Сохранить решение',exact:true}).click();
 await page.getByText('В этом фильтре замечаний нет.',{exact:true}).waitFor();
 assert.equal(await page.locator('#save-status').innerText(),'Решение сохранено');
 await page.locator('#finding-filter').selectOption('all');
 pass('saving a decision works when its card leaves the active filter');
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:path.join(output,'02-review.png'),fullPage:true});
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#download-report').click();
 const download=await downloadPromise;
 const downloaded=path.join(output,'downloaded-report.md');await download.saveAs(downloaded);
 assert.equal(await readFile(downloaded,'utf8'), await readFile(path.join(fixtures,'kiker-january-conflict-1.md'),'utf8'));
 pass('download keeps the generated report unchanged');
 await page.locator('#new-review').click();
 await page.locator('#import-file').setInputFiles(path.join(fixtures,'kiker-january-corrected-1.json'));
 await page.locator('#review-view').waitFor({state:'visible'});
 assert.equal(await page.locator('#metric-total').innerText(),'0');
 const correctedId=(await page.locator('#download-report').getAttribute('href')).split('/')[3];
 pass('corrected document shows zero findings');
 await page.locator('#open-compare').click();
 await page.locator('#compare-before').selectOption(conflictId);
 await page.locator('#compare-after').selectOption(correctedId);
 await page.locator('#compare-form button[type=submit]').click();
 await page.getByRole('heading',{name:'Не повторилось · 1',exact:true}).waitFor();
 assert.equal(await page.getByRole('heading',{name:'Новое · 0',exact:true}).count(),1);
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:path.join(output,'03-comparison.png'),fullPage:true});
 pass('comparison distinguishes absent, matched and new findings');
 await page.setViewportSize({width:390,height:844});
 await page.locator('#new-review').click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:path.join(output,'04-mobile-upload.png'),fullPage:true});
 await page.locator('#history .history-item').filter({hasText:'1 замечание'}).first().click();
 await page.locator('#review-view').waitFor({state:'visible'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:path.join(output,'05-mobile-review.png'),fullPage:true});
 pass('390px layout has no horizontal overflow');
 assert.deepEqual(errors,[]);pass('no browser script errors');
 await writeFile(path.join(output,'checks.json'),JSON.stringify({source:'automated browser check; no human participants',checks,errors},null,2)+'\n');
} finally {await context.close();await browser.close();}
